// Prova di «Cerca»: nomi trovati sul telefono, anche senza rete; la mappa va al posto scelto.
// Uso: CHROMIUM=<percorso> node tests/cerca.mjs <url-app> <cartella-uscita>   (TELEFONO=android per Android)
import { chromium, devices, webkit } from "playwright";
const [base, uscita] = process.argv.slice(2);
const android = process.env.TELEFONO === "android";
const tel = android ? "android" : "iphone";
let ok = 0, ko = 0;
const verifica = (cosa, c, d = "") => { if (c) { ok++; console.log("  ✓", cosa); } else { ko++; console.log("  ✗", cosa, d); } };
const b = android ? await chromium.launch({ executablePath: process.env.CHROMIUM || undefined }) : await webkit.launch();
const ctx = await b.newContext({ ...(android ? devices["Pixel 7"] : { viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true }), locale: "it-IT" });
const p = await ctx.newPage();
const errori = [], esterni = new Set();
p.on("pageerror", (e) => errori.push(String(e)));
p.on("console", (m) => { if (m.type() === "error" && !m.text().includes("GL Driver") && !m.text().startsWith("Failed to load resource")) errori.push(m.text()); });
p.on("request", (r) => { const h = new URL(r.url()).host; if (r.url().startsWith("http") && h !== new URL(base).host) esterni.add(h); });
const foto = async (n) => { await p.waitForTimeout(600); await p.screenshot({ path: `${uscita}/${tel}_${n}.png` }); };
await p.goto(`${base}?centro=7.62,44.39&zoom=10`);
await p.waitForSelector("body[data-mappa-pronta='1']", { timeout: 120000 });
await p.locator("button[aria-label='Chiudi il consiglio']").click({ timeout: 3000 }).catch(() => {});
await p.evaluate(() => navigator.serviceWorker?.ready);
await p.reload(); await p.waitForSelector("body[data-mappa-pronta='1']", { timeout: 120000 });
await p.locator("button[aria-label='Chiudi il consiglio']").click({ timeout: 3000 }).catch(() => {});
await foto("50_barra_cerca");
const cerca = async (testo) => {
  if (!(await p.locator(".campo-cerca").count())) await p.locator(".barra-cerca").click();
  await p.locator(".campo-cerca").fill(testo);
  await p.waitForTimeout(700);
  return p.locator(".riga-cerca").evaluateAll((r) => r.map((x) => x.innerText.replace(/\n/g, " | ")));
};
let r = await cerca("entrac");
verifica("«entrac» → Entracque per primo", /^Entracque \| paese/.test(r[0] ?? ""), r.slice(0, 3).join(" ; "));
await foto("51_risultati");
await p.locator(".riga-cerca").first().click();
await p.waitForTimeout(2000);
const c = await p.evaluate(() => { const m = globalThis.bole.mappa; return [m.getCenter().lng, m.getCenter().lat, m.getZoom()]; });
verifica("la mappa va su Entracque", Math.abs(c[0] - 7.397) < 0.03 && Math.abs(c[1] - 44.24) < 0.03 && c[2] >= 12.9, c.join(", "));
verifica("c'è il segno sul posto", await p.locator(".segno-cerca").count() === 1);
await foto("52_sulla_mappa");
await ctx.setOffline(true);
r = await cerca("sant anna");
verifica("senza rete: «sant anna» trova Sant'Anna…", r.length > 3 && r.every((x) => /^Sant.?Anna/i.test(x)), r.slice(0, 4).join(" ; "));
verifica("…con il paese vicino per distinguerle", r.some((x) => / vicino a /.test(x)), r.slice(0, 4).join(" ; "));
await foto("53_senza_rete_omonimi");
r = await cerca("cuneo");
verifica("«cuneo» → Cuneo città per prima", /^Cuneo \| città/.test(r[0] ?? ""), r.slice(0, 3).join(" ; "));
r = await cerca("qwzx");
verifica("nome inesistente: avviso, nessun risultato", r.length === 0 && (await p.locator(".nota-cerca").innerText()).includes("Nessun nome"));
await p.locator(".campo-cerca").fill("");
await p.waitForTimeout(300);
r = await p.locator(".riga-cerca").evaluateAll((x) => x.map((y) => y.innerText));
verifica("campo vuoto: i cercati di recente", /Entracque/.test(r[0] ?? ""), r.join(";"));
await foto("54_recenti");
await ctx.setOffline(false);
verifica("nessuna richiesta fuori dal sito", esterni.size === 0, [...esterni].join(", "));
verifica("nessun errore", errori.length === 0, errori.join("\n"));
await b.close();
console.log(`\n${ok} controlli passati, ${ko} falliti`);
if (ko) process.exit(1);
